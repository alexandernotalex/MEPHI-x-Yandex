# На тестовом полигоне для беспилотного автомобиля установлена
# неограниченная последовательность контрольных точек
# (светофоров).
#
# Каждая точка циклически меняет состояния:
# 1. "Разрешено" (зелёный) — 27 секунд.
# 2. "Предупреждение" (жёлтый) — 3 секунды.
# 3. "Запрещено" (красный) — 17 секунд.
# 4. "Предупреждение" (жёлтый) — 3 секунды.
# Затем цикл повторяется.
#
# Автомобиль вынужден остановиться при начале жёлтого
# сигнала после зелёного.
#
# При жёлтом сигнале после красного автомобиль может
# начинать движение.
#
# Случайная величина X — количество пройденных точек
# до первой остановки.
#
# Найти дисперсию X.
#
# Предполагаем, что состояние каждой контрольной точки
# при подъезде независимо от состояний предыдущих точек,
# а вероятности состояний пропорциональны их длительности.
# ============================================================

import numpy as np

# Продолжительность полного цикла
green = 27
yellow_after_green = 3
red = 17
yellow_after_red = 3

total_time = green + yellow_after_green + red + yellow_after_red

# Вероятность проезда
p_pass = (green + yellow_after_red) / total_time

# Вероятность остановки
p_stop = (yellow_after_green + red) / total_time

# Теоретическая дисперсия геометрического распределения
variance_theoretical = (1 - p_stop) / (p_stop ** 2)

# Проверка методом Монте-Карло
np.random.seed(42)

n_simulations = 1_000_000

# np.random.geometric считает количество испытаний
# до первого успеха, включая само успешное испытание.
# Вычитаем 1, чтобы получить количество пройденных точек.
X = np.random.geometric(
    p=p_stop,
    size=n_simulations
) - 1

# Оценка дисперсии по результатам моделирования
variance_simulation = np.var(X, ddof=1)

# Вывод результатов
print("Продолжительность цикла:", total_time)
print("Вероятность проезда:", p_pass)
print("Вероятность остановки:", p_stop)
print("Теоретическая дисперсия:", variance_theoretical)
print("Дисперсия по моделированию:", variance_simulation)
