# Файл data.csv содержит шесть колонок и 10 000 строк.
# В каждой колонке данные сгенерированы по некоторому
# закону распределения.
#
# Необходимо найти медиану данных из шестой колонки
# column_6.
#
# Ответ округлить до целого числа.
# ============================================================

import pandas as pd
import numpy as np

# 1. Загружаем данные
df = pd.read_csv("data.csv")

# 2. Выбираем шестую колонку
x = df["column_6"]

# 3. Вычисляем медиану
median = np.median(x)

# 4. Округляем результат до целого числа
answer = round(median)

# 5. Выводим результаты
print("Количество наблюдений:", len(x))
print("Медиана:", median)
print("Округлённый ответ:", answer)