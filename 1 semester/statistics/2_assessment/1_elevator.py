# ============================================================
# Задание 6.1
#
# В системе управления лифтами офисного здания (50 этажей)
# используется алгоритм оптимизации, который случайным образом
# выбирает этаж для доставки пользователя.
#
# Лифт "для офисных сотрудников" обслуживает только следующие
# диапазоны этажей:
#
# 1. Стандартные офисы: этажи 10–19 (10 этажей).
# 2. Дирекция: этажи 35–44 (10 этажей).
#
# Всего доступных этажей: 20.
#
# Случайная величина X — номер этажа, на который отправляется
# лифт. Предполагается, что каждый доступный этаж выбирается
# с одинаковой вероятностью.
#
# Найти дисперсию случайной величины X.
# ============================================================

import numpy as np

# Создаём список всех доступных этажей
floors = list(range(10, 20)) + list(range(35, 45))

# Вычисляем математическое ожидание
mean = np.mean(floors)

# Вычисляем математическое ожидание квадрата
mean_squared = np.mean(np.array(floors) ** 2)

# Вычисляем дисперсию
variance = np.var(floors, ddof=0)

print("Количество доступных этажей:", len(floors))
print("Математическое ожидание:", mean)
print("Математическое ожидание квадрата:", mean_squared)
print("Дисперсия:", variance)