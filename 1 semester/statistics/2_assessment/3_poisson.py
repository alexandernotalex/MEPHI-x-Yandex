
# ============================================================
# ЗАДАНИЕ 6.3
#
# В каждой из двух независимых проверок число обнаруженных
# ошибок X имеет распределение Пуассона с параметром 4.
#
# Каждая ошибка независимо становится фатальной
# с вероятностью 0.2.
#
# Модель отклоняют в проверке, если найдена хотя бы одна
# фатальная ошибка.
#
# Необходимо найти вероятность того, что модель будет
# отклонена в обеих проверках.
#
# Ответ требуется округлить до двух знаков после запятой.
# ============================================================

import numpy as np
import math

# Задаём параметры задачи
lambda_poisson = 4
p_fatal = 0.2

# Вычисляем вероятность отсутствия фатальных ошибок
# в одной проверке
p_no_fatal = math.exp(-lambda_poisson * p_fatal)

# Вычисляем вероятность отклонения модели
# хотя бы из-за одной фатальной ошибки
p_reject = 1 - p_no_fatal

# Вычисляем вероятность отклонения в обеих
# независимых проверках
p_both_reject = p_reject ** 2

# Выводим аналитические результаты
print("Вероятность отсутствия фатальных ошибок:", p_no_fatal)
print("Вероятность отклонения в одной проверке:", p_reject)
print("Вероятность отклонения в обеих проверках:", p_both_reject)
print("Ответ с округлением:", round(p_both_reject, 2))


# ============================================================
# ПРОВЕРКА МЕТОДОМ МОНТЕ-КАРЛО
# ============================================================

np.random.seed(42)

n_simulations = 1_000_000

# Генерируем количество ошибок в двух проверках.
# Строка — отдельная симуляция, столбец — проверка.
errors = np.random.poisson(
    lam=lambda_poisson,
    size=(n_simulations, 2)
)

# Генерируем количество фатальных ошибок
# из общего числа обнаруженных ошибок.
fatal_errors = np.random.binomial(
    n=errors,
    p=p_fatal
)

# Проверяем, была ли хотя бы одна фатальная ошибка
# в каждой из двух проверок.
rejected = fatal_errors > 0

# Нас интересуют симуляции, в которых модель отклонена
# одновременно в обеих проверках.
both_rejected = np.all(rejected, axis=1)

# Оцениваем искомую вероятность
p_simulation = np.mean(both_rejected)

print("\nРезультаты моделирования:")
print("Вероятность по Монте-Карло:", p_simulation)
